import {writeFile} from 'node:fs/promises';
import {releaseWindow} from '../physics.js';
const vines=[{x:150,y:32,length:150,area:0,hard:false}];const windows=[];
for(let i=1;i<=40;i++){
 const from=vines[i-1],hard=i>=4&&i%5===4,area=Math.min(7,Math.floor(i/5));
 const to={x:0,y:32+[0,-8,8,0,5][i%5],length:[150,158,146,154,150][i%5],area,hard};
 const desired=hard?(i<15?.13:i<30?.10:.085):.27;
 let best=null;
 for(let gap=190;gap<=285;gap++){
  to.x=from.x+gap;const w=releaseWindow(from,to,.01);if(w.seconds<=0)continue;
  const delta=Math.abs(w.seconds-desired);if(!best||delta<best.delta)best={gap,delta,...w};
 }
 if(!best)throw Error(`Unreachable ${i}`);to.x=from.x+best.gap;
 const measured=releaseWindow(from,to,.0025);to.windowMs=Math.round(measured.seconds*1000);vines.push(to);windows.push({from:i-1,to:i,hard,gap:best.gap,...measured});
}
await writeFile(new URL('../course.js',import.meta.url),`// Generated by npm run calibrate; geometry is deterministic.\nexport const VINES = ${JSON.stringify(vines,null,2)};\n`);
await writeFile(new URL('../course-validation.json',import.meta.url),JSON.stringify(windows,null,2)+'\n');
console.log(JSON.stringify({transitions:windows.length,normalMs:windows.filter(x=>!x.hard).map(x=>Math.round(x.seconds*1000)),hardMs:windows.filter(x=>x.hard).map(x=>Math.round(x.seconds*1000))}));
